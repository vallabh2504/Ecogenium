# ───────────────────────────────────────────────────────────────────────────────
# Generic constant-cruise / gentle-accel / elevation-adaptive profile builder.
# Same physics & terminal-stop logic as combined_best_profile._build_lap, but the
# in-lap target is a CRUISE SPEED held by a closed-loop power command rather than
# a pulse/glide band. This lets us express families B/C/D/E.
# ───────────────────────────────────────────────────────────────────────────────

def _cruise_power(v, vtarget, grade, a_cap):
    """Electrical power to track a cruise target: hold load + bounded accel term.
    Commands accel up to a_cap toward vtarget; coasts (P=0) when at/above target."""
    if v >= vtarget - 0.05:
        # hold speed (no accel) — pure road load
        return _hold_power(v, grade)
    # accelerate gently toward target
    a_need = min(a_cap, (vtarget - v) / max(DT, 0.2))
    F = 0.5*CD*AF*RHO*v*v + CRR*MASS*G + MASS*G*grade + MASS*a_need
    # Convert the desired tractive FORCE to a power command. P = F·v underflows to
    # zero at standstill (so the car would never launch); floor the speed at the
    # SAME 0.3 m/s that _net_force uses for P·η/max(v,0.3), so the commanded power
    # reproduces F (capped at the motor's F_max) right down to v=0.
    return max(0., F*max(v, 0.3)/ETA_DT)


def _build_lap_cruise(v_cruise, a_accel, k_grade=0., const_power=None):
    """One lap: gentle accel -> hold cruise -> coast -> hard-brake to a stop.

    v_cruise   : steady cruise speed [m/s] (flat-road target).
    a_accel    : max acceleration during the launch ramp [m/s^2].
    k_grade    : elevation-adaptive gain. >0 lowers target on climbs / raises on
                 descents (ease off uphill, let it run downhill). 0 = flat target.
    const_power: if not None, command CONSTANT electrical power [W] during the
                 cruise phase instead of constant speed (family E). Speed then
                 floats with grade; capped at V_MAX.
    """
    tl=[];vl=[];Pl=[];sl=[];el=[];gl=[];coastl=[]
    t=v=s=0.; first=True; pP=0.; mode='ACCEL'
    while True:
        sw=s%D_LAP; grade=float(_grade_fn(sw)); elev=float(_elev_fn(sw))
        v_tg=float(np.clip(v_cruise - k_grade*grade, 3.0, V_MAX))
        rem=D_LAP-sw; Pt=0.; vc=V_MAX
        # terminal stop: coast when remaining == natural coast dist; hard-brake below V_COAST_STOP
        if mode not in ('COAST_TO_STOP','HARD_BRAKE') and v>0 and rem<800.:
            if rem<=_coast_dist(v,s): mode='COAST_TO_STOP'
        if mode=='COAST_TO_STOP' and v<=V_COAST_STOP: mode='HARD_BRAKE'

        if mode in ('COAST_TO_STOP','HARD_BRAKE'):
            Pt=0.; vc=V_MAX
        elif const_power is not None and v>= (v_tg-0.5):
            # constant-power cruise: command fixed electrical power, speed floats
            Pt=float(const_power); vc=V_MAX; mode='CRUISE_CP'
        else:
            Pt=_cruise_power(v, v_tg, grade, a_accel)
            vc=v_tg if v < v_tg else V_MAX
            mode='ACCEL' if v < v_tg-0.05 else 'CRUISE'

        P=float(np.clip(Pt,pP-P_RAMP_MAX,pP+P_RAMP_MAX)); pP=P
        if not first:
            tl.append(t);vl.append(v);Pl.append(P);sl.append(sw)
            el.append(elev);gl.append(grade)
            coastl.append(mode in ('COAST_TO_STOP','HARD_BRAKE'))
        first=False
        if mode=='HARD_BRAKE':
            vn=max(0.,v-A_HARD*DT); sn=s+v*DT
        else:
            a=_net_force(v,P,grade)/MASS
            vn=float(np.clip(v+a*DT,0.,vc)); sn=s+v*DT
        t+=DT; v=vn; s=sn
        if (mode=='HARD_BRAKE' and v==0.) or t>800.: break
    se=sl[-1] if sl else 0.; ee=el[-1] if el else float(_elev_fn(0)); ge=gl[-1] if gl else 0.
    for _ in range(N_STOP_STEPS):
        tl.append(t);vl.append(0.);Pl.append(0.);sl.append(se)
        el.append(ee);gl.append(ge);coastl.append(True);t+=DT
    return tl,vl,Pl,sl,el,gl,coastl


def build_profile_cruise(v_cruise, a_accel, k_grade=0., const_power=None):
    """Tile the cruise lap over 11 laps; smooth velocity like build_profile()."""
    at=[];av=[];aP=[];as_=[];aln=[];ae=[];ag=[];ac=[]; to=0.
    for lap in range(1,N_LAPS+1):
        tl,vl,Pl,sl,el,gl,coastl=_build_lap_cruise(v_cruise,a_accel,k_grade,const_power)
        ta=np.array(tl)+to
        at.append(ta);av.append(np.array(vl));aP.append(np.array(Pl))
        as_.append(np.array(sl));aln.append(np.full(len(tl),lap,dtype=int))
        ae.append(np.array(el));ag.append(np.array(gl))
        ac.append(np.array(coastl,dtype=bool)); to=float(ta[-1])+DT
    ta=np.concatenate(at);va=np.concatenate(av);Pa=np.concatenate(aP)
    sa=np.concatenate(as_);la=np.concatenate(aln);ea=np.concatenate(ae)
    ga=np.concatenate(ag);ca=np.concatenate(ac)
    vs=va.copy(); im=(va>0.)
    ss=np.where(np.diff(np.concatenate([[0],im.astype(int)]))==1)[0]
    se_=np.where(np.diff(np.concatenate([im.astype(int),[0]]))==-1)[0]+1
    for ms,me in zip(ss,se_):
        seg=va[ms:me]
        if len(seg)>25: vs[ms:me]=savgol_filter(seg,21,2)
        vs[ms:me]=np.clip(vs[ms:me],0.,V_MAX)
    return ta,vs,Pa,sa,la,ea,ga,ca


# ───────────────────────────────────────────────────────────────────────────────
# Scoring: run Strategy G auto-tuned to CS, compute km/m3 + diagnostics.
# ───────────────────────────────────────────────────────────────────────────────

def _motor_eta_stats(va, ga):
    """Time fraction the motor spends in high-eta (>=0.80) vs low-eta region, and
    mean motor eta weighted by motor-on time. Uses the measured map exactly as the
    plant does (compute_motor_signals)."""
    accel = np.gradient(va, DT)
    P_wheel = (CRR*MASS*G*va + 0.5*CD*AF*RHO*va**3 + MASS*accel*va + MASS*G*ga*va)
    P_wheel_pos = np.maximum(P_wheel, 0.)
    v_safe = np.maximum(va, 0.3)
    Torque = (P_wheel_pos / v_safe) * R_WHEEL
    RPM = va * RPM_PER_MS
    moving = (P_wheel_pos > 1.0) & (va > 0.3)
    eta = motor_eta_rt(RPM, Torque)
    eta_on = eta[moving]
    if len(eta_on) == 0:
        return 0., 0., 0.
    f_hi = float(np.mean(eta_on >= 0.80))
    return float(np.mean(eta_on)), f_hi, float(np.sum(moving)*DT)


def _energy_breakdown(va, ga, ca):
    """Decompose where mechanical energy goes over the whole race [Joules].
    aero, rolling, the 11 brake KE losses (no regen), and net grade (~0 on a loop)."""
    accel = np.gradient(va, DT)
    E_aero = float(np.sum(0.5*CD*AF*RHO*va**3) * DT)
    E_roll = float(np.sum(CRR*MASS*G*va) * DT)
    E_grade = float(np.sum(MASS*G*ga*va) * DT)
    # brake KE loss: KE at the instant hard-brake begins, summed over laps.
    # detect transitions into braking by velocity going to 0 while coasting flagged.
    # simpler & robust: sum positive KE dissipated where decel happens during ca
    # (coast+brake) — but coast aero/roll is already counted; the *brake* loss is
    # the residual KE dumped when the car is forced to 0. Compute per-lap as KE at
    # V_COAST_STOP times number of stops (hard-brake from V_COAST_STOP).
    KE_brake = 0.5*MASS*V_COAST_STOP**2 * N_LAPS
    return dict(E_aero=E_aero, E_roll=E_roll, E_grade=E_grade, KE_brake=KE_brake)


def score_profile(name, family, params, ta, va, Pa, sa, la, ea, ga, ca, verbose=True):
    ok, d, dur, stops = verify(ta, va, la)
    if not ok:
        if verbose:
            print(f"  [INVALID] {name:32s} d={d:.2f}km dur={dur:.1f}min stops={stops}")
        return None
    P_e, _, _ = compute_motor_signals(va, ga)
    Kp, r = bisect_kp(P_e, la, ca, name)
    km3 = km_per_m3(r)
    cs = abs(r['dSOC']) <= 0.015
    mean_eta, f_hi, t_on = _motor_eta_stats(va, ga)
    eb = _energy_breakdown(va, ga, ca)
    # FC electrical energy actually delivered (proxy for H2 path)
    E_fc = r['E_fc_J']
    peak_v = float(np.max(va))
    cruise_v = float(np.median(va[va > 0.5*peak_v])) if peak_v > 0 else 0.
    rec = dict(name=name, family=family, params=params, km3=km3, H2=r['m_H2'],
               H2n=r['m_H2_norm'], dSOC=r['dSOC'], cs=cs, dur=dur, dist=d,
               peak_v=peak_v, cruise_v=cruise_v, mean_eta=mean_eta, f_hi=f_hi,
               t_on=t_on, E_fc=E_fc, Kp=Kp,
               ta=ta, va=va, Pa=Pa, sa=sa, la=la, ea=ea, ga=ga, ca=ca,
               SOC=r['SOC'], Pfc=r['Pfc'], Psc=r['Psc'], **eb)
    if verbose:
        flag = 'CS ' if cs else 'no '
        print(f"  >>> {name:32s} km/m3={km3:6.1f}  H2={r['m_H2']:.3f}g  dSOC={r['dSOC']:+.4f} "
              f"[{flag}] dur={dur:.1f}m vmax={peak_v*3.6:.1f}km/h eta_m={mean_eta*100:.1f}% f_hi={f_hi*100:.0f}%")
    return rec


