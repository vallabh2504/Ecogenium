def run_sweeps():
    results = []

    print("\n" + "="*78)
    print("FAMILY A — Pulse-and-Glide (current). Includes the documented baseline.")
    print("="*78)
    V_DH = 10.5
    # baseline validation point first (VH=10/VL=6/PP=1400):
    png_grid = []
    png_grid.append((10.0, 6.0, 1400., 0.))   # documented ~235 baseline
    for VH in [9.5, 10.0, 10.5, 11.0]:
        for VL in [5.5, 6.0, 6.5, 7.0]:
            if VL >= VH-1.5: continue
            for PP in [1200., 1400., 1600.]:
                png_grid.append((VH, VL, PP, 0.))
    # elevation-adaptive PnG (family D within PnG): k_grade band-shift
    for kg in [40., 80., 120.]:
        png_grid.append((9.5, 7.0, 1200., kg))
    seen=set()
    for VH, VL, PP, kg in png_grid:
        key=(VH,VL,PP,kg)
        if key in seen: continue
        seen.add(key)
        ta,va,Pa,sa,la,ea,ga,ca = build_profile(VH,VL,V_DH,PP,1200.,k_grade=kg)
        nm=f"PnG VH{VH} VL{VL} PP{PP:.0f}"+(f" kg{kg:.0f}" if kg else "")
        fam='A-PnG' if kg==0 else 'D-PnG-elev'
        rec=score_profile(nm, fam, dict(VH=VH,VL=VL,PP=PP,k_grade=kg),
                          ta,va,Pa,sa,la,ea,ga,ca)
        if rec: results.append(rec)

    print("\n" + "="*78)
    print("FAMILY B/C — Constant-cruise + coast-to-stop (gentle vs brisk accel).")
    print("="*78)
    for vcr in [7.0, 7.5, 8.0, 8.5, 9.0, 9.5, 10.0, 11.0]:
        for a in [0.25, 0.5, 1.0, 2.0]:   # gentle -> brisk launch
            ta,va,Pa,sa,la,ea,ga,ca = build_profile_cruise(vcr, a)
            nm=f"Cruise v{vcr} a{a}"
            rec=score_profile(nm,'BC-cruise',dict(v_cruise=vcr,a_accel=a),
                              ta,va,Pa,sa,la,ea,ga,ca)
            if rec: results.append(rec)

    print("\n" + "="*78)
    print("FAMILY D — Elevation-adaptive constant-cruise (modulate target by grade).")
    print("="*78)
    for vcr in [8.0, 8.5, 9.0]:
        for kg in [60., 120., 200.]:
            ta,va,Pa,sa,la,ea,ga,ca = build_profile_cruise(vcr, 0.5, k_grade=kg)
            nm=f"CruiseElev v{vcr} kg{kg:.0f}"
            rec=score_profile(nm,'D-cruise-elev',dict(v_cruise=vcr,k_grade=kg),
                              ta,va,Pa,sa,la,ea,ga,ca)
            if rec: results.append(rec)

    print("\n" + "="*78)
    print("FAMILY E — Constant-POWER cruise (speed floats with grade).")
    print("="*78)
    for pwr in [350., 450., 550., 650.]:
        for vcr in [8.5, 9.5]:
            ta,va,Pa,sa,la,ea,ga,ca = build_profile_cruise(vcr, 0.5, const_power=pwr)
            nm=f"ConstPwr P{pwr:.0f} vcap{vcr}"
            rec=score_profile(nm,'E-const-power',dict(P=pwr,v_cap=vcr),
                              ta,va,Pa,sa,la,ea,ga,ca)
            if rec: results.append(rec)

    return results


def main():
    results = run_sweeps()
    if not results:
        raise RuntimeError("No valid profiles found.")

    # rank: prefer CS, then km/m3
    valid_cs = [r for r in results if r['cs']]
    ranked = sorted(valid_cs or results, key=lambda r: -r['km3'])

    print("\n" + "="*100)
    print("RANKED TABLE (charge-sustaining only)" + ("" if valid_cs else "  [no CS runs — showing all]"))
    print("="*100)
    hdr = f"{'#':>2} {'profile':34s} {'family':14s} {'km/m3':>7} {'H2[g]':>7} {'dSOC':>8} {'dur':>5} {'vmax':>6} {'eta_m':>6} {'f_hi':>5}"
    print(hdr)
    print("-"*100)
    for i, r in enumerate(ranked[:15], 1):
        print(f"{i:>2} {r['name']:34s} {r['family']:14s} {r['km3']:7.1f} {r['H2']:7.3f} "
              f"{r['dSOC']:+8.4f} {r['dur']:5.1f} {r['peak_v']*3.6:6.1f} "
              f"{r['mean_eta']*100:6.1f} {r['f_hi']*100:5.0f}")

    best = ranked[0]
    # find best PnG and best cruise for the verdict margin
    png = [r for r in (valid_cs or results) if r['family'] in ('A-PnG','D-PnG-elev')]
    cruise = [r for r in (valid_cs or results) if r['family'] in ('BC-cruise','D-cruise-elev','E-const-power')]
    best_png = max(png, key=lambda r: r['km3']) if png else None
    best_cruise = max(cruise, key=lambda r: r['km3']) if cruise else None

    print("\n" + "="*100)
    print("VERDICT")
    print("="*100)
    if best_png:
        print(f"Best PnG    : {best_png['name']:34s} km/m3={best_png['km3']:.1f}  "
              f"eta_m={best_png['mean_eta']*100:.1f}%  f_hi={best_png['f_hi']*100:.0f}%")
    if best_cruise:
        print(f"Best cruise : {best_cruise['name']:34s} km/m3={best_cruise['km3']:.1f}  "
              f"eta_m={best_cruise['mean_eta']*100:.1f}%  f_hi={best_cruise['f_hi']*100:.0f}%")
    if best_png and best_cruise:
        margin = best_png['km3'] - best_cruise['km3']
        winner = "PULSE-AND-GLIDE" if margin > 0 else "CONSTANT-CRUISE"
        print(f"\nWINNER: {winner}  (margin = {abs(margin):.1f} km/m3, "
              f"{abs(margin)/max(best_cruise['km3'],best_png['km3'])*100:.1f}%)")

    print("\nEnergy breakdown of overall best profile (whole race, mechanical J):")
    tot = best['E_aero']+best['E_roll']+best['KE_brake']+max(best['E_grade'],0)
    print(f"  aero drag    : {best['E_aero']/1000:8.1f} kJ ({best['E_aero']/tot*100:4.1f}%)")
    print(f"  rolling res. : {best['E_roll']/1000:8.1f} kJ ({best['E_roll']/tot*100:4.1f}%)")
    print(f"  brake KE loss: {best['KE_brake']/1000:8.1f} kJ ({best['KE_brake']/tot*100:4.1f}%) (11 stops, no regen)")
    print(f"  net grade    : {best['E_grade']/1000:8.1f} kJ (loop ~0)")
    print(f"  FC elec energy delivered (race): {best['E_fc']/1000:.1f} kJ")

    # ── Figure ──────────────────────────────────────────────────────────────────
    fig = plt.figure(figsize=(15, 11), dpi=130)
    gs = fig.add_gridspec(2, 1, height_ratios=[1.1, 1.0], hspace=0.32)

    # winning velocity profile (lap 1) + elevation
    ax = fig.add_subplot(gs[0]); axe = ax.twinx()
    m1 = best['la'] == 1
    t1 = best['ta'][m1]-best['ta'][m1][0]
    v1 = best['va'][m1]*3.6
    e1 = best['ea'][m1]
    # also overlay the best of the OTHER family for contrast
    other = best_cruise if best['family'].startswith(('A','D-PnG')) else best_png
    ax.plot(t1, v1, color='#D55E00', lw=2.2, label=f"WINNER: {best['name']} ({best['km3']:.1f} km/m3)")
    if other is not None:
        mo = other['la']==1
        to=other['ta'][mo]-other['ta'][mo][0]; vo=other['va'][mo]*3.6
        ax.plot(to, vo, color='#0072B2', lw=1.6, ls='--', alpha=0.8,
                label=f"Best other: {other['name']} ({other['km3']:.1f} km/m3)")
    axe.fill_between(t1, e1, np.min(e1), color='#BB3311', alpha=0.12)
    axe.plot(t1, e1, color='#BB3311', lw=0.9, alpha=0.5)
    axe.set_ylabel('Elevation [m]', color='#BB3311', fontsize=10)
    ax.set_xlabel('Time in lap [s]', fontsize=11)
    ax.set_ylabel('Velocity [km/h]', fontsize=11)
    ax.set_title('Winning velocity profile vs best alternative family (Lap 1) + elevation',
                 fontsize=12, fontweight='bold')
    ax.legend(loc='upper right', fontsize=9)
    ax.grid(alpha=0.25)

    # km/m3 ranking bar chart (top ~12)
    ax2 = fig.add_subplot(gs[1])
    top = ranked[:12]
    names = [r['name'] for r in top]
    vals = [r['km3'] for r in top]
    fam_color = {'A-PnG':'#D55E00','D-PnG-elev':'#E69F00','BC-cruise':'#0072B2',
                 'D-cruise-elev':'#56B4E9','E-const-power':'#009E73'}
    cols = [fam_color.get(r['family'], '#888') for r in top]
    y = np.arange(len(top))
    ax2.barh(y, vals, color=cols)
    ax2.set_yticks(y); ax2.set_yticklabels(names, fontsize=8)
    ax2.invert_yaxis()
    ax2.set_xlabel('km / m3 H2 (CS-normalised)', fontsize=11)
    ax2.set_title('Top profiles across all families (color = family)', fontsize=12, fontweight='bold')
    for i, v in enumerate(vals):
        ax2.text(v+0.3, i, f"{v:.1f}", va='center', fontsize=8)
    ax2.set_xlim(min(vals)-5, max(vals)+6)
    handles = [plt.Rectangle((0,0),1,1,color=c) for c in fam_color.values()]
    ax2.legend(handles, list(fam_color.keys()), fontsize=8, loc='lower right')
    ax2.grid(alpha=0.25, axis='x')

    out = os.path.join(C.RESULTS_DIR, 'profile_optimization.png')
    fig.savefig(out, dpi=130, bbox_inches='tight', facecolor='white')
    plt.close(fig)
    print(f"\nFigure -> {out}")
    print("\nDONE.")


if __name__ == '__main__':
    main()
